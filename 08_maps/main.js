// Практика 8: последовательный ввод ключей и значений коллекции Map.
do {
  const studyMap = new Map(); // Создаёт пустую коллекцию пар «ключ — значение».

  // За один шаг вводятся ключ и его значение; confirm предлагает добавить следующую пару.
  do {
    const key = prompt("Введите ключ, например course:", "course"); // Ключ вводится обычным текстом.
    if (key === null) {
      break; // Отмена заканчивает ввод; уже добавленные пары сохраняются.
    }
    const value = prompt("Введите значение для ключа «" + key + "»:", "JavaScript");
    if (value === null) {
      break; // Незавершённая пара не добавляется в коллекцию.
    }
    studyMap.set(key, value); // Добавляет пару; повтор того же ключа заменяет его прежнее значение.
  } while (confirm("Добавить ещё одну пару?\nОК — да, Отмена — нет."));

  let message = ""; // Здесь собираются строки для одного окна результата.
  for (const key of studyMap.keys()) {
    const value = studyMap.get(key); // get получает значение по ключу; keys возвращает ключи в порядке добавления.
    const line = `Ключ — ${key}, значение — ${value}`; // Обратные кавычки позволяют подставлять значения через ${...}.
    console.log(line); // Каждая пара выводится отдельной записью по условию задания.
    message += line + "\n"; // Добавляет пару и перенос строки в сообщение.
  }
  if (studyMap.size === 0) {
    message = "Коллекция пуста."; // size показывает число пар в Map.
    console.log(message);
  }
  alert(message);
} while (confirm("Создать другую коллекцию?\nОК — да, Отмена — нет.")); // Для нового запуска создаётся новая пустая Map.
