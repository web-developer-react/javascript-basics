// Практика 1: ввод числа, проверка чётности и вывод ответа в окно и консоль.
// do...while запускает задание один раз, а затем предлагает повторить его.
do {
  const input = prompt("Введите целое число:", "8"); // prompt возвращает строку или null при нажатии «Отмена».
  if (input === null) {
    console.log("Ввод отменён.");
    alert("Ввод отменён.");
    break; // Завершает цикл, если пользователь отменил ввод.
  }

  const number = +input; // Унарный плюс превращает введённую строку в число.
  let message; // Здесь будет храниться готовый ответ.

  // typeof проверяет тип; isNaN обнаруживает неудачное преобразование текста в число.
  if (input.trim() === "" || typeof number !== "number" || isNaN(number)) {
    message = "Упс, кажется, вы ошиблись"; // trim убирает пробелы по краям; пустой ввод не считается нулём.
  } else if (number % 1 !== 0) {
    message = "Введите целое число"; // У целого числа остаток от деления на 1 равен нулю.
  } else if (number % 2 === 0) {
    message = "Число чётное"; // Остаток от деления на 2 равен нулю.
  } else {
    message = "Число нечётное"; // Сюда попадают в том числе отрицательные нечётные числа.
  }

  console.log(message); // Ответ остаётся в консоли браузера.
  alert(message); // Тот же ответ показывается во всплывающем окне.
} while (confirm("Проверить другое число?\nОК — да, Отмена — нет.")); // confirm возвращает true для ОК и false для отмены.
