// Практика 2: ввод простого значения и определение его типа с помощью typeof.
do {
  const input = prompt("Введите число, текст, true, false или null.\nКавычки и скобки не нужны.", "42");
  if (input === null) {
    console.log("Ввод отменён.");
    alert("Ввод отменён.");
    break; // Кнопка «Отмена» отличается от введённого слова null.
  }

  // prompt возвращает текст; несколько простых условий превращают известные записи в нужные значения.
  let x = input.trim(); // Убирает пробелы в начале и конце введённого текста.
  if (x === "true") {
    x = true; // Слово true становится логическим значением «истина».
  } else if (x === "false") {
    x = false; // Слово false становится логическим значением «ложь».
  } else if (x === "null") {
    x = null; // null означает отсутствие значения и попадёт в последнюю ветку проверки типа.
  } else if (x !== "" && !isNaN(x)) {
    x = +x; // Непустая числовая запись становится числом; остальной текст остаётся строкой.
  }

  let message;
  if (typeof x === "number") {
    message = "x — число"; // typeof возвращает название типа в виде строки.
  } else if (typeof x === "string") {
    message = "x — строка";
  } else if (typeof x === "boolean") {
    message = "x — логический тип";
  } else {
    message = "Тип x не определён"; // Фраза из условия для остальных типов.
  }

  console.log("Значение x:", x); // Показывает, какое значение получилось после преобразования.
  console.log(message);
  alert(message);
} while (confirm("Проверить другое значение?\nОК — да, Отмена — нет.")); // ОК повторяет ввод, отмена завершает задание.
