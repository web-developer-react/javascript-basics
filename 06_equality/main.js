// Практика 6: проверка, одинаковы ли введённые через запятую элементы.
do {
  const input = prompt("Введите элементы через запятую.\nНапример: кот, кот, кот", "кот, кот, кот");
  if (input === null) {
    console.log("Ввод отменён.");
    alert("Ввод отменён.");
    break;
  }

  let items = [];
  if (input.trim() !== "") {
    items = input.split(","); // Получаем массив строк; цифры в этом задании тоже сравниваются как текст.
  }
  let allEqual = true; // Предполагаем, что отличий нет, пока не найдём хотя бы одно.

  // Начинаем со второго элемента и сравниваем его с первым, убрав пробелы по краям.
  for (let index = 1; index < items.length; index += 1) {
    if (items[index].trim() !== items[0].trim()) {
      allEqual = false; // Строки «кот» и «Кот», а также «5» и «05» различаются.
      break; // После первого различия дальнейший поиск не нужен.
    }
  }

  console.log(allEqual); // Для пустого массива и одного элемента результат остаётся true.
  if (allEqual) {
    alert("Все элементы одинаковы: да (true).");
  } else {
    alert("Все элементы одинаковы: нет (false).");
  }
} while (confirm("Проверить другой массив?\nОК — да, Отмена — нет."));
