// Практика 7: подсчёт чётных чисел, нечётных чисел и нулей среди записей через запятую.
do {
  const input = prompt("Введите числа через запятую.\nМожно добавить текст — он будет пропущен. Дробную часть пишите через точку.", "0, 1, 2, 3, 4, текст, null, -5, -2, 0");
  if (input === null) {
    console.log("Ввод отменён.");
    alert("Ввод отменён.");
    break;
  }

  const items = input.split(","); // Получаем массив текстовых записей для последовательной проверки.
  let evenCount = 0; // Чётные числа, кроме нулей.
  let oddCount = 0; // Нечётные числа.
  let zeroCount = 0; // Нули считаются отдельно по условию задания.

  for (const item of items) {
    const value = item.trim(); // Убирает пробелы вокруг очередной записи.
    if (value === "" || isNaN(value)) {
      continue; // Пропускает пустые записи и текст, который нельзя превратить в число.
    }
    const number = +value; // Числовая запись превращается в число только после проверки.
    if (number % 1 !== 0) {
      continue; // Пропускает дроби и бесконечность: у них остаток при делении на 1 не равен нулю.
    }

    if (number === 0) {
      zeroCount += 1; // Ноль проверяется первым и не увеличивает счётчик остальных чётных.
    } else if (number % 2 === 0) {
      evenCount += 1; // Остаток от деления на 2 равен нулю.
    } else {
      oddCount += 1; // Считает также отрицательные нечётные числа.
    }
  }

  console.log("Чётных: " + evenCount);
  console.log("Нечётных: " + oddCount);
  console.log("Нулей: " + zeroCount);
  alert("Чётных: " + evenCount + "\nНечётных: " + oddCount + "\nНулей: " + zeroCount); // Те же результаты показываются в одном окне.
} while (confirm("Посчитать другой массив?\nОК — да, Отмена — нет."));
