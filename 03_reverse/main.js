// Практика 3: разворот обычного текста методами массива.
do {
  const text = prompt("Введите строку, которую нужно развернуть:", "Hello");
  if (text === null) {
    console.log("Ввод отменён.");
    alert("Ввод отменён.");
    break; // Отмена завершает программу, а пустая строка остаётся допустимым вводом.
  }

  const letters = text.split(""); // Разбивает строку на элементы массива; обычные буквы становятся отдельными элементами.
  letters.reverse(); // Меняет порядок элементов массива на обратный.
  const result = letters.join(""); // Соединяет элементы без запятых: Hello превращается в olleH.

  // Это простой учебный способ: некоторые эмодзи состоят из нескольких частей и могут развернуться некорректно.
  console.log(result);
  if (result === "") {
    alert("Результат — пустая строка.");
  } else {
    alert(result);
  }
} while (confirm("Развернуть другую строку?\nОК — да, Отмена — нет.")); // Выбор пользователя управляет повторением.
