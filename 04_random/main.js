// Практика 4: случайное целое число от 0 до 100, включая обе границы.
// Здесь ввод числа не нужен: программа выбирает его сама.
do {
  const randomNumber = Math.floor(Math.random() * 101); // random даёт число от 0 до 1 без единицы; floor округляет вниз, получаем 0–100.
  console.log(randomNumber); // Новый запуск добавляет запись в консоль; одинаковые результаты тоже возможны.
  alert("Случайное число: " + randomNumber);
} while (confirm("Сгенерировать ещё одно число?\nОК — да, Отмена — нет.")); // ОК продолжает цикл, отмена останавливает его.
