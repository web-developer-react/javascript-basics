// Практика 5: ввод элементов через запятую, вывод длины массива и каждого элемента.
do {
  const input = prompt("Введите элементы через запятую.\nНапример: яблоко, груша, слива", "яблоко, груша, слива");
  if (input === null) {
    console.log("Ввод отменён.");
    alert("Ввод отменён.");
    break;
  }

  let items = []; // Пустой ввод оставляет массив пустым.
  if (input.trim() !== "") {
    items = input.split(","); // Каждая запятая разделяет элементы; все введённые элементы остаются строками.
  }
  console.log(items.length); // length показывает количество элементов.
  let message = "Количество элементов: " + items.length; // Начало общего сообщения для alert.

  // forEach выполняет функцию для каждого элемента; index — его номер, начиная с нуля.
  items.forEach(function (item, index) {
    const value = item.trim(); // Убирает пробелы по краям отдельного элемента.
    console.log(value); // Каждый элемент выводится отдельной записью, как требует задание.
    message += "\n" + index + ": " + value; // Добавляет новую строку в общее сообщение.
  });
  alert(message);
} while (confirm("Ввести другой массив?\nОК — да, Отмена — нет.")); // ОК возвращает к вводу элементов.
